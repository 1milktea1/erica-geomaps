"""Build the geographic reference files in ../data from authoritative boundaries.

Source: Bangladesh Subnational Administrative Boundaries (COD-AB), Bangladesh
Bureau of Statistics (BBS) via OCHA / HDX, licence CC BY-IGO.
https://data.humdata.org/dataset/cod-ab-bgd

The app only needs the files this script writes (data/locations.csv and
data/upazilas_subset.geojson); run it again only to refresh them.

Usage:
    python scripts/build_reference.py                 # downloads (~33 MB)
    python scripts/build_reference.py --zip path.zip  # use an already-downloaded shp zip
"""
from __future__ import annotations

import argparse
import datetime as dt
import tempfile
import zipfile
from pathlib import Path

import geopandas as gpd
import pandas as pd
import requests

HDX_PACKAGE_API = "https://data.humdata.org/api/3/action/package_show?id=cod-ab-bgd"
DATA_DIR = Path(__file__).resolve().parent.parent / "data"

# Survey spelling -> (official BBS upazila name, parent district).
# The district is part of the key so that e.g. "Sherpur" resolves to Sherpur
# Upazila in Bogura, not Sherpur Sadar in Sherpur district.
SURVEY_TO_UPAZILA = {
    "Chilmari": ("Chilmari", "Kurigram", ""),
    "Fulcchari": ("Fulchhari", "Gaibandha", "Survey spelling 'Fulcchari'; official BBS spelling 'Fulchhari'."),
    "Kurigram Sadar": ("Kurigram Sadar", "Kurigram", ""),
    "Sadullapur": ("Sadullapur", "Gaibandha", ""),
    "Sariakandi": ("Sariakandi", "Bogura", ""),
    "Sherpur": ("Sherpur", "Bogura",
                "INFERRED: Sherpur Upazila (Bogura), chosen because the other six locations are riverine "
                "upazilas in Kurigram/Gaibandha/Bogura. Not Sherpur Sadar (Sherpur district)."),
    "Sughatta": ("Saghata", "Gaibandha", "Survey spelling 'Sughatta'; official BBS spelling 'Saghata'."),
}
# Extra spellings seen in DESDR files (e.g. Sliders static/admin_raw.parquet uses 'Fulchhari').
EXTRA_ALIASES = {
    "Fulcchari": ["Fulchhari", "Fulchari", "Phulchhari"],
    "Sughatta": ["Saghata", "Shaghata"],
}
# Sanity box around the Brahmaputra-Jamuna study area.
LAT_RANGE, LON_RANGE = (24.5, 26.0), (89.2, 89.9)


def download_zip(dest: Path) -> tuple[Path, str]:
    meta = requests.get(HDX_PACKAGE_API, timeout=60).json()["result"]
    res = next(r for r in meta["resources"] if r["name"] == "bgd_admin_boundaries.shp.zip")
    print(f"Downloading {res['url']}")
    with requests.get(res["url"], stream=True, timeout=600) as r:
        r.raise_for_status()
        with open(dest, "wb") as f:
            for chunk in r.iter_content(1 << 20):
                f.write(chunk)
    return dest, res["url"]


def build(zip_path: Path, source_url: str) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        with zipfile.ZipFile(zip_path) as z:
            z.extractall(tmp)
        adm3 = gpd.read_file(Path(tmp) / "bgd_admin3.shp").to_crs(4326)

    rows, polys = [], []
    for survey_name, (upazila, district, note) in SURVEY_TO_UPAZILA.items():
        hit = adm3[(adm3.adm3_name == upazila) & (adm3.adm2_name == district)]
        if len(hit) != 1:
            raise SystemExit(f"Expected exactly 1 match for {survey_name}, got {len(hit)}")
        rec = hit.iloc[0]
        pt = rec.geometry.representative_point()  # guaranteed inside the polygon
        lat, lon = round(pt.y, 5), round(pt.x, 5)
        if not (LAT_RANGE[0] <= lat <= LAT_RANGE[1] and LON_RANGE[0] <= lon <= LON_RANGE[1]):
            raise SystemExit(f"{survey_name} point {lat},{lon} outside expected study area")
        aliases = sorted({survey_name, upazila, *EXTRA_ALIASES.get(survey_name, [])})
        rows.append({
            "survey_name": survey_name,
            "aliases": "|".join(aliases),
            "upazila": upazila,
            "district": district,
            "division": rec.adm1_name,
            "adm3_pcode": rec.adm3_pcode,
            "lat": lat,
            "lon": lon,
            "area_sqkm": round(float(rec.area_sqkm), 1),
            "source": "BBS/OCHA COD-AB bgd_admin3 (HDX cod-ab-bgd), representative point of polygon",
            "note": note,
        })
        polys.append({"survey_name": survey_name, "upazila": upazila, "district": district,
                      "adm3_pcode": rec.adm3_pcode, "geometry": rec.geometry})

    DATA_DIR.mkdir(exist_ok=True)
    pd.DataFrame(rows).to_csv(DATA_DIR / "locations.csv", index=False)
    gdf = gpd.GeoDataFrame(polys, crs=4326)
    gdf["geometry"] = gdf.geometry.simplify(0.0005, preserve_topology=True)  # ~50 m, keeps file small
    gdf.to_file(DATA_DIR / "upazilas_subset.geojson", driver="GeoJSON")

    (DATA_DIR / "SOURCES.md").write_text(f"""# Geographic reference sources

`locations.csv` and `upazilas_subset.geojson` were generated by `scripts/build_reference.py`
on {dt.date.today().isoformat()}.

- **Dataset:** Bangladesh – Subnational Administrative Boundaries (COD-AB), layer `bgd_admin3` (upazila)
- **Publisher:** Bangladesh Bureau of Statistics (BBS), distributed by OCHA on HDX
- **Page:** https://data.humdata.org/dataset/cod-ab-bgd
- **File:** {source_url}
- **Licence:** Creative Commons Attribution for Intergovernmental Organisations (CC BY-IGO)

Marker coordinates are the polygon's `representative_point()` (always inside the upazila),
not a hand-entered coordinate. Polygons are simplified to ~0.0005° for display only.
See the `note` column of `locations.csv` for spelling differences and the Sherpur inference.
""")
    print(pd.DataFrame(rows)[["survey_name", "upazila", "district", "adm3_pcode", "lat", "lon"]].to_string(index=False))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", type=Path, help="Existing bgd_admin_boundaries.shp.zip")
    args = ap.parse_args()
    if args.zip:
        build(args.zip, "https://data.humdata.org/dataset/cod-ab-bgd (bgd_admin_boundaries.shp.zip)")
    else:
        with tempfile.TemporaryDirectory() as tmp:
            path, url = download_zip(Path(tmp) / "bgd_shp.zip")
            build(path, url)


if __name__ == "__main__":
    main()
